/** Vanilla JS per export HTML (dopo import THREE in initModel3dLayers). */
export function model3dInteractionVanillaJsLines(indent = "  "): string[] {
  const b = `${indent}  `;
  return [
    `${indent}function __model3dRunInteraction(root, rule) {`,
    `${b}if (!rule || !rule.enabled) return;`,
    `${b}const axis = rule.axis || 'y';`,
    `${b}const dur = Math.max(0.05, rule.duration ?? 0.6);`,
    `${b}const ease = rule.ease || 'power2.out';`,
    `${b}const kind = rule.kind;`,
    `${b}const amount = rule.amount ?? 90;`,
    `${b}const deg = Math.PI / 180;`,
    `${b}if (!root.userData.__model3dInteractionToggle) root.userData.__model3dInteractionToggle = {};`,
    `${b}const toggles = root.userData.__model3dInteractionToggle;`,
    `${b}const rotAmt = amount * deg;`,
    `${b}if (kind === 'rotateRelative') {`,
    `${b}  gsap.to(root.rotation, { [axis]: '+=' + rotAmt, duration: dur, ease });`,
    `${b}  return;`,
    `${b}}`,
    `${b}if (kind === 'rotateToggle') {`,
    `${b}  const on = !toggles[rule.id];`,
    `${b}  toggles[rule.id] = on;`,
    `${b}  gsap.to(root.rotation, { [axis]: '+=' + (on ? rotAmt : -rotAmt), duration: dur, ease });`,
    `${b}  return;`,
    `${b}}`,
    `${b}if (kind === 'scalePulse') {`,
    `${b}  gsap.to(root.scale, { [axis]: amount, duration: dur / 2, ease, yoyo: true, repeat: 1 });`,
    `${b}  return;`,
    `${b}}`,
    `${b}if (kind === 'scaleToggle') {`,
    `${b}  const on = !toggles[rule.id];`,
    `${b}  toggles[rule.id] = on;`,
    `${b}  gsap.to(root.scale, { [axis]: on ? amount : 1, duration: dur, ease });`,
    `${b}  return;`,
    `${b}}`,
    `${b}if (kind === 'moveRelative') {`,
    `${b}  gsap.to(root.position, { [axis]: '+=' + amount, duration: dur, ease });`,
    `${b}}`,
    `${indent}}`,
    `${indent}function __model3dInteractionHit(rule, root, event, camera, dom) {`,
    `${b}if (rule.hit === 'viewport') return true;`,
    `${b}const rect = dom.getBoundingClientRect();`,
    `${b}const x = ((event.clientX - rect.left) / rect.width) * 2 - 1;`,
    `${b}const y = -((event.clientY - rect.top) / rect.height) * 2 + 1;`,
    `${b}const rc = new THREE.Raycaster();`,
    `${b}rc.setFromCamera(new THREE.Vector2(x, y), camera);`,
    `${b}const hits = rc.intersectObject(root, true);`,
    `${b}if (!hits.length) return false;`,
    `${b}const needle = (rule.meshName || '').trim();`,
    `${b}if (!needle) return true;`,
    `${b}return hits.some((h) => {`,
    `${b}  const name = (h.object.name || '').trim();`,
    `${b}  return name === needle || h.object.uuid === needle;`,
    `${b}});`,
    `${indent}}`,
    `${indent}function __bindModel3dInteractions(targetId, interactions, root, camera, canvas, sceneCfg, viewW, viewH) {`,
    `${b}if (!interactions || !interactions.enabled) return;`,
    `${b}const rules = (interactions.rules || []).filter((r) => r.enabled);`,
    `${b}if (!rules.length) return;`,
    `${b}const runMatching = (trigger, ev) => {`,
    `${b}  rules.filter((r) => r.trigger === trigger).forEach((rule) => {`,
    `${b}    if (!__model3dInteractionHit(rule, root, ev, camera, canvas)) return;`,
    `${b}    __model3dRunInteraction(root, rule);`,
    `${b}    __fitModel3dCamera(camera, root, viewW, viewH, sceneCfg);`,
    `${b}  });`,
    `${b}};`,
    `${b}if (rules.some((r) => r.trigger === 'click')) {`,
    `${b}  canvas.addEventListener('click', (ev) => runMatching('click', ev));`,
    `${b}  canvas.style.cursor = 'pointer';`,
    `${b}}`,
    `${b}if (rules.some((r) => r.trigger === 'doubleClick')) {`,
    `${b}  canvas.addEventListener('dblclick', (ev) => runMatching('doubleClick', ev));`,
    `${b}}`,
    `${b}if (rules.some((r) => r.trigger === 'pointerenter')) {`,
    `${b}  canvas.addEventListener('pointerenter', (ev) => runMatching('pointerenter', ev));`,
    `${b}}`,
    `${b}if (rules.some((r) => r.trigger === 'pointerleave')) {`,
    `${b}  canvas.addEventListener('pointerleave', (ev) => runMatching('pointerleave', ev));`,
    `${b}}`,
    `${indent}}`,
  ];
}