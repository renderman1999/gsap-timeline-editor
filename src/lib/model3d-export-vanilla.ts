import {
  MODEL3D_ENV_HDRI_BASE,
  MODEL3D_ENV_HDRI_FILE,
} from "@/lib/model3d-env";

/** Helper vanilla da inserire dentro initModel3dLayers dopo import THREE. */
export function model3dExportVanillaHelperLines(indent = "  "): string[] {
  const b = `${indent}  `;
  const envJson = JSON.stringify({
    base: MODEL3D_ENV_HDRI_BASE,
    files: MODEL3D_ENV_HDRI_FILE,
  });

  return [
    `${indent}const __model3dEnvFiles = ${envJson};`,
    `${indent}function __upgradeModel3dMaterials(root) {`,
    `${b}root.traverse((child) => {`,
    `${b}  if (!child.isMesh) return;`,
    `${b}  const upgradeOne = (mat) => {`,
    `${b}    if (mat.isMeshStandardMaterial || mat.isMeshPhysicalMaterial) return mat;`,
    `${b}    const basic = mat.isMeshBasicMaterial || mat.isMeshLambertMaterial || mat.isMeshPhongMaterial ? mat : null;`,
    `${b}    const color = basic?.color ? basic.color.clone() : new THREE.Color(0xffffff);`,
    `${b}    const map = basic && basic.map ? basic.map : undefined;`,
    `${b}    return new THREE.MeshStandardMaterial({`,
    `${b}      color,`,
    `${b}      map,`,
    `${b}      transparent: mat.transparent,`,
    `${b}      opacity: mat.opacity,`,
    `${b}      roughness: 0.65,`,
    `${b}      metalness: 0.1,`,
    `${b}    });`,
    `${b}  };`,
    `${b}  if (Array.isArray(child.material)) {`,
    `${b}    child.material = child.material.map(upgradeOne);`,
    `${b}  } else {`,
    `${b}    const next = upgradeOne(child.material);`,
    `${b}    if (next !== child.material) child.material = next;`,
    `${b}  }`,
    `${b}});`,
    `${indent}}`,
    `${indent}function __fitModel3dDirectionalShadow(light, root) {`,
    `${b}const box = new THREE.Box3().setFromObject(root);`,
    `${b}if (box.isEmpty()) return;`,
    `${b}const size = box.getSize(new THREE.Vector3());`,
    `${b}const maxDim = Math.max(size.x, size.y, size.z, 0.5);`,
    `${b}const half = maxDim * 1.4;`,
    `${b}const center = box.getCenter(new THREE.Vector3());`,
    `${b}light.target.position.copy(center);`,
    `${b}light.target.updateMatrixWorld();`,
    `${b}const cam = light.shadow.camera;`,
    `${b}if (cam && cam.isOrthographicCamera) {`,
    `${b}  cam.left = -half;`,
    `${b}  cam.right = half;`,
    `${b}  cam.top = half;`,
    `${b}  cam.bottom = -half;`,
    `${b}  cam.near = 0.25;`,
    `${b}  cam.far = maxDim * 6 + 5;`,
    `${b}  cam.updateProjectionMatrix();`,
    `${b}}`,
    `${indent}}`,
    `${indent}async function __loadModel3dEnvironment(renderer, scene, sceneCfg) {`,
    `${b}const preset = sceneCfg.envPreset || 'studio';`,
    `${b}const file = (__model3dEnvFiles.files[preset] || __model3dEnvFiles.files.studio);`,
    `${b}const url = __model3dEnvFiles.base + file;`,
    `${b}const { RGBELoader } = await import('three/addons/loaders/RGBELoader.js');`,
    `${b}const pmrem = new THREE.PMREMGenerator(renderer);`,
    `${b}pmrem.compileEquirectangularShader();`,
    `${b}const hdr = await new RGBELoader().loadAsync(url);`,
    `${b}const envMap = pmrem.fromEquirectangular(hdr).texture;`,
    `${b}scene.environment = envMap;`,
    `${b}const intensity = sceneCfg.envIntensity ?? 0.85;`,
    `${b}if ('environmentIntensity' in scene) scene.environmentIntensity = intensity;`,
    `${b}scene.traverse((obj) => {`,
    `${b}  if (!obj.isMesh) return;`,
    `${b}  const mats = Array.isArray(obj.material) ? obj.material : [obj.material];`,
    `${b}  mats.forEach((mat) => {`,
    `${b}    if (mat && 'envMapIntensity' in mat) mat.envMapIntensity = intensity;`,
    `${b}  });`,
    `${b}});`,
    `${b}hdr.dispose();`,
    `${b}pmrem.dispose();`,
    `${indent}}`,
    `${indent}function __addModel3dContactShadow(scene, groundY, sceneCfg, maxDim) {`,
    `${b}if (!sceneCfg.shadowContact || (sceneCfg.contactOpacity ?? 0) <= 0) return;`,
    `${b}const opacity = sceneCfg.contactOpacity ?? 0.4;`,
    `${b}const scaleSetting = sceneCfg.contactScale ?? 12;`,
    `${b}const blur = sceneCfg.contactBlur ?? 2.5;`,
    `${b}const planeSize = Math.max(maxDim * (scaleSetting / 12) * 1.12, maxDim * 0.65);`,
    `${b}const texSize = 256;`,
    `${b}const canvas = document.createElement('canvas');`,
    `${b}canvas.width = canvas.height = texSize;`,
    `${b}const ctx = canvas.getContext('2d');`,
    `${b}if (!ctx) return;`,
    `${b}const c = texSize / 2;`,
    `${b}const soft = Math.min(1, Math.max(0, blur / 8));`,
    `${b}const g = ctx.createRadialGradient(c, c, 0, c, c, c);`,
    `${b}g.addColorStop(0, 'rgba(0,0,0,' + opacity + ')');`,
    `${b}g.addColorStop(0.08 + soft * 0.12, 'rgba(0,0,0,' + (opacity * 0.55) + ')');`,
    `${b}g.addColorStop(0.35 + soft * 0.4, 'rgba(0,0,0,' + (opacity * 0.12) + ')');`,
    `${b}g.addColorStop(1, 'rgba(0,0,0,0)');`,
    `${b}ctx.fillStyle = g;`,
    `${b}ctx.fillRect(0, 0, texSize, texSize);`,
    `${b}const map = new THREE.CanvasTexture(canvas);`,
    `${b}map.colorSpace = THREE.SRGBColorSpace;`,
    `${b}const mat = new THREE.MeshBasicMaterial({`,
    `${b}  map,`,
    `${b}  transparent: true,`,
    `${b}  depthWrite: false,`,
    `${b}  toneMapped: false,`,
    `${b}});`,
    `${b}const mesh = new THREE.Mesh(new THREE.PlaneGeometry(planeSize, planeSize), mat);`,
    `${b}mesh.rotation.x = -Math.PI / 2;`,
    `${b}mesh.position.y = groundY + 0.001;`,
    `${b}mesh.renderOrder = 2;`,
    `${b}scene.add(mesh);`,
    `${indent}}`,
  ];
}